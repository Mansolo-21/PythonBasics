#tuple -are ordered ,unchangeable and allow duplicates
courses=("HTML","CSS","Python","Bootstrap","JavaScript")
print(courses)
print(type(courses))

#accessing tuple items
print(courses[0])

#len()
print(len(courses))

#loop
for x in courses:
    print(x)

#tuple()
digits=tuple((1,2,3,4,5))
print(digits)
print(type(digits))
for x in digits:
    print(x)

