#Logical Operators (and or not)
#and-returns only if both conditions are true
z=10
print(z<20 and z>5)
print(z<20 and z>15)

#or-returns if either condition is true
print(z<20 or z>15)

#not-returns the opposite of the condition
print(not(z>5))

#assignment operators =, +=, -=, *=
b=40
print(b)

#+=
b+=5 #b=b+5
print(b)

#-=
b-=10 #b=b-10
print(b)

#*=
